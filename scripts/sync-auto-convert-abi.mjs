// Generated from the exact locally compiled protocol release, not hand-maintained tuples.
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
const root = resolve(process.argv[2] || '../protocol');
const names = ['OrderedDepositsFacet', 'AutoConvertFacet', 'AutoConvertAdminFacet', 'AutoConvertPolicyFacet', 'AutoConvertViewFacet', 'SiloRedemptionFacet'];
const artifact = name => JSON.parse(readFileSync(`${root}/out/${name}.sol/${name}.json`)).abi;
const abis = names.flatMap(artifact);
abis.push(...artifact('WhitelistFacet').filter(x => x.type === 'function' && x.name === 'whitelistTokenWithAutoConvertPolicy'));
for (const name of ['LibOrderedDeposits', 'LibAutoConvert', 'LibAutoConvertStable2', 'LibAutoConvertStable2Policy', 'LibAutoConvertWellSafety']) {
  abis.push(...artifact(name).filter(x => x.type === 'error' || x.type === 'event'));
}
const seen = new Set();
const abi = abis.filter(x => {
  const key = JSON.stringify([x.type, x.name, x.inputs]);
  if (seen.has(key) || !['function', 'event', 'error'].includes(x.type)) return false;
  seen.add(key); return true;
});
writeFileSync('src/constants/abi/autoConvertABI.ts', `// Generated by scripts/sync-auto-convert-abi.mjs. Do not edit.\nexport const autoConvertABI = ${JSON.stringify(abi, null, 2)} as const;\n`);
console.log(`Synced ${abi.length} auto-convert/index ABI entries.`);
const sowABI = artifact('SowBlueprint').filter(x => x.type === 'function' && x.name === 'sowBlueprint');
if (sowABI.length !== 1) throw new Error('Expected the release SowBlueprint entry point');
writeFileSync('src/constants/abi/tractorReleaseABI.ts', `// Generated by scripts/sync-auto-convert-abi.mjs. Do not edit.\nexport const sowReleaseABI = ${JSON.stringify(sowABI, null, 2)} as const;\n`);
